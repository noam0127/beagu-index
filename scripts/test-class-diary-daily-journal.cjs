/* Daily journal choices after each chapter's outcome; old saves remain loadable. */
'use strict';
const assert=require('node:assert/strict');
const diary=require('../js/class-diary-daily-journal-v1.js');
assert.deepEqual(diary.validate(),{chapters:36,options:108});
const state={phase:'semester_reflection',episode:16,history:Array.from({length:16},(_,i)=>({episode:i+1,choice:0}))};
assert.equal(diary.selection(state,16),null);
const s=diary.choose(state,2);
assert.equal(diary.selection(s,16),2);
assert.equal(s.journal.length,1);
assert.equal(diary.selection(state,16),null);
assert.match(diary.note(s,16).text,/공평/);
const changed=diary.choose(s,0);
assert.equal(changed.journal.length,1);
assert.equal(diary.selection(changed,16),0);
assert.equal(diary.entries(changed).length,1);
for(let i=1;i<=36;i++)assert.equal(diary.choices(i).length,3);
assert.throws(()=>diary.choose({...state,phase:'semester_chapter'},0),/JOURNAL_REFLECTION_REQUIRED/);
assert.throws(()=>diary.choose(state,4),/JOURNAL_REFLECTION_REQUIRED/);
assert.equal(diary.selection({phase:'semester_reflection',episode:16,history:[]},16),null);
const fs=require('node:fs'),path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../teacher-class-diary-play.html'),'utf8');
assert(html.includes('js/class-diary-daily-journal-v1.js'));
assert(html.includes('id="dailyJournal"'));
assert(html.includes('dailyJournal.choose(game,choice.id)'));
assert(html.includes('dailyJournal.selection(game,game.episode)'));
console.log('PASS: 36 daily journal prompts, 108 diary options, reselect, legacy state, page wiring');

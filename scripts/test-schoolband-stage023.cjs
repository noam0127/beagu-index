#!/usr/bin/env node
"use strict";
// 023 data/state tests only: NO listening, sound playback, paid APIs or rights outreach.
const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict"),vm=require("node:vm");
const ROOT=path.resolve(__dirname,".."),CHARTS=path.join(ROOT,"games/nangam-schoolband-v08/charts");
const queue=JSON.parse(fs.readFileSync(path.join(CHARTS,"song-queue-stage023.v1.json"),"utf8"));
const rights=JSON.parse(fs.readFileSync(path.join(CHARTS,"song-intake-rights.v1.json"),"utf8"));
const Q=require("./schoolband-stage023-queue.cjs"),R=require("./schoolband-stage023-queue-runner.cjs");
const GAME=fs.readFileSync(path.join(ROOT,"games/nangam-schoolband-v08/index.html"),"utf8");
const clone=o=>JSON.parse(JSON.stringify(o));
let passed=0;
function yes(fn,label){fn();passed++;}
function no(fn,code){assert.throws(fn,e=>e?.code===code,code);passed++;}
const root=queue.records.find(x=>x.song_id==="original-shining-our-school");
const second=queue.records.find(x=>x.song_id==="original-meter-shift-exercise-014");
yes(()=>assert.equal(Q.validateQueue(queue,rights).count,2),"two recorded");
yes(()=>assert.equal(Q.validateQueue(queue,rights).schoolAnthemCount,0),"zero school anthms");
yes(()=>assert.deepEqual(Q.validateQueue(queue,rights).trialSongs,["original-shining-our-school"]),"only original trial");
yes(()=>assert.equal(Q.replayAudit(root,rights),"trial_available"),"original audit");
yes(()=>assert.equal(Q.replayAudit(second,rights),"private_ready"),"second original audit");
yes(()=>assert.equal(Q.isTrustedOriginal(root,rights),true),"original trust match");
yes(()=>assert.equal(Q.isTrustedOriginal(second,rights),true),"other original trust match");
yes(()=>assert.equal(Q.resolvePlaytestSong(queue,rights,"7004971","volleyball").songId,root.song_id),"original resolution");
yes(()=>assert.equal(Q.resolvePlaytestSong(queue,rights,"7004971","anthem").song,"volleyball"),"unregistered anthem fallback");
yes(()=>assert.equal(Q.resolvePlaytestSong(queue,rights,"7004971","anthem").schoolAnthemPlayable,false),"no real anthem release");
yes(()=>assert.equal(Q.resolvePlaytestSong(queue,rights,"7004971","fake").song,null),"no unknown song");
const altered=clone(queue);
altered.records[0].kind="school_anthem";
no(()=>Q.validateQueue(altered,rights),"external_school_song_not_enabled");
const fake=clone(queue);
fake.records[0].school_id="S000123";
no(()=>Q.validateQueue(fake,rights),"external_school_song_not_enabled");
const forged=clone(queue);
forged.records[0].source_sha="0".repeat(40);
no(()=>Q.validateQueue(forged,rights),"source_not_trusted");
const selfApproved=clone(queue);
selfApproved.records.push({...root,song_id:"external-school-anthem",school_id:"S000123",kind:"original_internal"});
no(()=>Q.validateQueue(selfApproved,rights),"external_school_song_not_enabled");
const dup=clone(queue);
dup.records.push(clone(root));
no(()=>Q.validateQueue(dup,rights),"duplicate_song_id");
const auditLost=clone(queue);
auditLost.records[0].audit=[];
no(()=>Q.validateQueue(auditLost,rights),"audit_missing");
const auditForged=clone(queue);
auditForged.records[0].stage="private_ready";
no(()=>Q.validateQueue(auditForged,rights),"stage_audit_mismatch");
const auditSeq=clone(queue);
auditSeq.records[0].audit[1].seq=99;
no(()=>Q.validateQueue(auditSeq,rights),"audit_sequence_invalid");
const earlyRelease=clone(queue);
earlyRelease.records[1].audit.push({seq:4,event:"release_trial",date:"2026-11-23"});
earlyRelease.records[1].stage="trial_available";
no(()=>Q.validateQueue(earlyRelease,rights),"embedded_original_only");
const trialWithdrawal=Q.advance(root,"withdraw",rights);
yes(()=>assert.equal(trialWithdrawal.stage,"withdrawn"),"take down original");
yes(()=>assert.equal(trialWithdrawal.audit.at(-1).seq,root.audit.length+1),"audit monotonic");
const taken={...queue,records:[trialWithdrawal,second]};
yes(()=>assert.equal(Q.validateQueue(taken,rights).trialSongs.length,0),"withdrawn never available");
yes(()=>assert.equal(Q.resolvePlaytestSong(taken,rights,"7004971","volleyball").song,null),"no invalid fallback to withdrawn original");
yes(()=>assert.equal(Q.resolvePlaytestSong(taken,rights,"7004971","anthem").song,null),"anthem fallback must not circumvent withdrawal");
no(()=>Q.advance(trialWithdrawal,"release_trial",rights),"invalid_state_transition");
no(()=>Q.advance(trialWithdrawal,"approve_private",rights),"invalid_state_transition");
const secondTaken=Q.advance(second,"withdraw",rights);
yes(()=>assert.equal(secondTaken.stage,"withdrawn"),"no permission needed for take down");
yes(()=>assert.equal(Q.resolvePlaytestSong({...queue,records:[root,secondTaken]},rights,"7004971","anthem").song,"volleyball"),"other song withdraw keeps safe original");
const started=Q.advance({song_id:root.song_id,...root,stage:"none",audit:[]},"submit",rights);
yes(()=>assert.equal(started.stage,"pending"),"submission");
const reviewing=Q.advance(started,"start_review",rights);
yes(()=>assert.equal(reviewing.stage,"reviewing"),"review");
const approved=Q.advance(reviewing,"approve_private",rights);
yes(()=>assert.equal(approved.stage,"private_ready"),"private approve");
yes(()=>assert.equal(Q.advance(approved,"release_trial",rights).stage,"trial_available"),"private release");
yes(()=>assert.equal(Q.advance(reviewing,"reject",rights).stage,"rejected"),"reject");
no(()=>Q.advance(reviewing,"release_trial",rights),"invalid_state_transition");
no(()=>Q.advance({...approved,review:{data_checked:false,approved_for_trial:true}},"release_trial",rights),"data_review_required");
const oldRights=clone(rights);
oldRights.records[0].public_approved=true;
no(()=>Q.validateQueue(queue,oldRights),"source_not_trusted");
const missingRights=clone(rights);
missingRights.records=missingRights.records.slice(1);
no(()=>Q.validateQueue(queue,missingRights),"source_not_trusted");
const runner=R.load();
yes(()=>assert.equal(runner.result.valid,true),"runner sha verification and queue validated");
yes(()=>assert.equal(R.simulate("withdraw",root.song_id).fallback.song,null),"runner withdrawal simulation");
yes(()=>assert.equal(R.simulate("withdraw",second.song_id).fallback.song,"volleyball"),"runner alternate withdrawal");
const script=GAME.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert(script);new vm.Script(script);passed++;
yes(()=>assert(GAME.includes('const REGISTERED_ANTHEMS=Object.freeze({});')),"no live school registry");
yes(()=>assert(GAME.includes('const PLAYABLE_SCHOOL_CHARTS=Object.freeze({});')),"no fake anthem chart");
yes(()=>assert(GAME.includes('if(selectedSong!=="volleyball")')),"start refuses unimplemented anthem");
yes(()=>assert(GAME.includes('getResolvedSongId:()=>selectedSong==="volleyball"?INTERNAL_PLAYTEST_SONG.song_id:null')),"original song ID in game");
yes(()=>assert(GAME.includes('const CHART_VERSION="creative-anthem-rhythm-v1.0.0";')),"version");
console.log("PASS stage023",passed,"queue state, withdrawal, forgery, rights, embedded original matching and no-sound checks");

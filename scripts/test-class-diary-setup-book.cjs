/* Four-screen settings book: static regression contract. No accounts or API. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const html=read('teacher-class-diary-play.html');
const journey=read('js/class-diary-journey-v1.js');
const paper=read('js/class-diary-setup-book-v1.js');
const css=read('styles/class-diary-setup-book-v1.css');
const motion=read('js/class-diary-motion-v1.js');
const pages=[...html.matchAll(/data-setup-screen="([1-4])"/g)].map(m=>Number(m[1]));
assert.deepEqual(pages,[1,2,3,4],'Setup screens must be four discrete, ordered pages');
for(let i=1;i<=4;i++)assert(html.includes('data-step-label="'+i+'"'),'Missing numbered page '+i);
assert(html.includes('id="setupTitle"'),'Every sheet must update its accessible title');
assert(html.includes('href="styles/class-diary-setup-book-v1.css'),'Paper CSS must load');
assert(html.includes('src="js/class-diary-setup-book-v1.js'),'Paper animation JS must load');
assert((html.match(/class="setup-supporting-person"/g)||[]).length===6,'Six supporting adults remain');
assert(html.includes('id="diarySchoolSearchDialog"'),'School chooser must remain available');
assert(html.includes('id="partner" required'),'Partner selection must remain required');
assert(html.includes('id="setupReviewPartner"'),'Choice review must remain');
assert(html.includes('class="primary setup-begin"'),'Story start button must remain');
assert(journey.includes('Math.min(4'),'Only four pages may be visited');
assert(journey.includes('ready(){if(step!==4)return false'),'Only final review may submit');
assert(journey.includes('validate(1)')&&journey.includes('validate(2)'),'School and person validation must survive');
assert(journey.includes('BeaguClassDiarySetupBook.turn'),'Both directions must call the page flip');
assert(paper.includes("to<from?'back':'next'"),'Backwards navigation must reverse paper turn');
assert(css.includes('@keyframes diary-setup-paper-next'),'Forward paper fold missing');
assert(css.includes('@keyframes diary-setup-paper-back'),'Backward paper fold missing');
assert(css.includes('@media(prefers-reduced-motion:reduce)'),'Motion-sensitive players must have reduced animation');
assert(motion.includes('4:setup.querySelector'),'Existing visual animation must cover fourth page');
for(const text of [journey,paper,css])assert(!/localStorage|sessionStorage|fetch\(/.test(text),'Settings motion must never store or transmit player choices');
console.log('PASS four-sheet settings: school → chosen colleague → supporting teachers → review; transitions, validation, reduced motion');

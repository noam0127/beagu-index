"""Real PostgreSQL 16 backup/restore on a new networkless fixture. No production access."""
import importlib.util
import os
import sys
import pathlib
import tempfile
import unittest

ROOT=pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"scripts/release-manager"))
spec=importlib.util.spec_from_file_location("integrated_backup",ROOT/"scripts/release-manager/integrated_backup.py")
b=importlib.util.module_from_spec(spec)
spec.loader.exec_module(b)
PINS=("a"*64,"b"*40,"c"*40)


class Checkpoint(unittest.TestCase):
    def test_private_actual_backup_restore_and_rejections(self):
        with b.FixtureCluster() as cluster, tempfile.TemporaryDirectory() as parent:
            root=pathlib.Path(parent)
            cluster.sql("fixture_source", """
CREATE ROLE fixture_reader;
CREATE SCHEMA beagu_private;
CREATE TABLE public.participation_codes(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text NOT NULL UNIQUE);
CREATE TABLE beagu_private.referral_profiles(id bigint PRIMARY KEY REFERENCES public.participation_codes(id), valid_referrals integer NOT NULL);
CREATE TABLE public.posts(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, author bigint REFERENCES public.participation_codes(id), body text);
ALTER TABLE public.posts ENABLE ROW LEVEL SECURITY;
CREATE POLICY fixture_read ON public.posts FOR SELECT TO fixture_reader USING (true);
GRANT SELECT ON public.posts TO fixture_reader;
INSERT INTO public.participation_codes(code) VALUES ('fixture-a'),('fixture-b');
INSERT INTO beagu_private.referral_profiles VALUES (1,1),(2,0);
INSERT INTO public.posts(author,body) VALUES (1,E'한글\\nline\\tend'),(2,'duplicate'),(2,'duplicate');
SELECT nextval(pg_get_serial_sequence('public.posts','id'));
""")
            a=root/"first";a.mkdir(mode=0o700)
            pin=b.checkpoint(cluster,a,*PINS)
            m,data=b.verify_checkpoint(a,pin,*PINS)
            self.assertEqual(m["fingerprint"]["tables"]["public.posts"]["count"],3)
            self.assertTrue(m["fingerprint"]["sequences"])
            self.assertEqual((a/"checkpoint.dump").stat().st_mode&0o777,0o600)
            with self.assertRaisesRegex(ValueError,"checkpoint_release_mismatch"):
                b.verify_checkpoint(a,pin,PINS[0],PINS[1],"d"*40)
            (a/"checkpoint.dump").write_bytes(data+b"corrupt")
            with self.assertRaisesRegex(ValueError,"backup_integrity_failure"):
                b.verify_checkpoint(a,pin,*PINS)
            (a/"checkpoint.dump").write_bytes(data)
            (a/"checkpoint.dump").chmod(0o644)
            with self.assertRaisesRegex(ValueError,"unsafe_checkpoint_file"):
                b.verify_checkpoint(a,pin,*PINS)
            (a/"checkpoint.dump").chmod(0o600)
            cluster.sql("fixture_source","UPDATE beagu_private.referral_profiles SET valid_referrals=2 WHERE id=1;")
            with self.assertRaisesRegex(ValueError,"stale_source_checkpoint"):
                b.rehearse_restore(cluster,a,pin,*PINS)
            c=root/"latest";c.mkdir(mode=0o700)
            latest=b.checkpoint(cluster,c,*PINS)
            self.assertNotEqual(latest,pin)
            with self.assertRaisesRegex(ValueError,"stale_or_tampered_checkpoint"):
                b.verify_checkpoint(a,latest,*PINS)
            private=root/"vault";private.mkdir(mode=0o700)
            key=os.urandom(32)
            encrypted_pin=b.encrypted_checkpoint(cluster,private,key,"fixture-key-1",*PINS)
            self.assertEqual([f.suffix for f in private.iterdir()],[".vault"])
            proof=b.rehearse_encrypted_restore(cluster,private,key,"fixture-key-1",encrypted_pin,*PINS)
            self.assertTrue(proof["encrypted"])
            self.assertTrue(proof["restore_verified"])
            self.assertFalse(proof["execution_enabled"])
            self.assertEqual(cluster.sql("fixture_restore","SELECT relrowsecurity FROM pg_class WHERE oid='public.posts'::regclass;").strip(),b"t")
            self.assertEqual(cluster.sql("fixture_restore","SELECT has_table_privilege('fixture_reader','public.posts','SELECT');").strip(),b"t")
            with self.assertRaises(RuntimeError):
                b.rehearse_restore(cluster,c,latest,*PINS)
            cluster.sql("fixture_restore","UPDATE public.posts SET body='tampered' WHERE id=1;")
            self.assertNotEqual(b.fingerprint(cluster,"fixture_restore"),b.fingerprint(cluster,"fixture_source"))
            with self.assertRaisesRegex(ValueError,"not_fixture_database"):
                cluster.sql("production","SELECT 1;")

if __name__=="__main__":unittest.main()

'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const sql=read('supabase/migrations/20261120_telemetry_visit_presence_guard.sql');
const visits=read('js/visit-stats.js');
const games=read('js/beagu-presence-games-v1.js');
const baseline=read('supabase/migrations/20261120_admin_hourly_live_presence.sql');
for(const [name,src] of [['visits',visits],['games',games]]) new vm.Script(src,{filename:name});
assert.match(sql,/create index if not exists beagu_visits_visitor_recent_v1_idx/);
assert.match(sql,/pg_advisory_xact_lock/);
assert.match(sql,/hashtextextended\(p_visitor::text/);
assert.match(sql,/visited_at >= now\(\) - interval '1 minute'\) >= 30/);
assert.match(sql,/visited_at >= now\(\) - interval '1 hour'\) >= 120/);
assert.match(sql,/event_id = p_event/);
assert.match(sql,/on conflict\(event_id\) do nothing/);
assert.match(sql,/rate_limited/);
assert.match(sql,/\[89ab\]/);
assert.match(sql,/when p_page in \('index','search','result','survey','challenge'\)/);
assert.match(sql,/on conflict \(visitor_id\) do update/);
assert.doesNotMatch(sql,/is distinct from excluded\.page/,'Page switching must not evade heartbeat cooldown');
assert.match(sql,/beagu_admin_accounts a/);
assert.match(sql,/revoke all on function public\.beagu_record_visit/);
assert.match(sql,/grant execute on function public\.beagu_presence_ping_v1/);
assert.match(baseline,/last_seen_at >= v_now - interval '5 minutes'/);
assert.match(visits,/const event = crypto\.randomUUID\(\)/);
assert.match(visits,/rpc\('beagu_record_visit'/);
assert.match(visits,/rpc\('beagu_presence_ping_v1'/);
assert.match(games,/rpc\('beagu_presence_ping_v1'/);
assert.match(read('admin.html'),/adminOnlineCount/);
console.log('PASS: telemetry guard preserves anonymous visit and live-presence contracts');

import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ctx=vm.createContext({window:{}});
for(const p of ['js/historical-questionnaire-choices.js','js/2025-observed-choices.js','js/2026-questionnaire-options-v1.2.js','js/school-facilities-v11126.js'])vm.runInContext(fs.readFileSync(p,'utf8'),ctx);
const F=ctx.window.BeaguSchoolFacilities,C=ctx.window.Beagu2026Questionnaire;
const m=(q,v)=>({year:2025,questionId:q,modeOption:v});
const r=(q,row,...values)=>({questionId:q,row,values});
const s=(q,...selectedOptions)=>({year:2025,questionId:q,selectedOptions});
const historical=[m('Q31','있다'),m('Q32','없다'),m('Q38','모름'),m('Q06','④ 1명 있다'),m('Q09','③ 1회'),m('Q02','② 1회')];
const selections=[s('Q03','교과서 구입'),s('Q04','안함')];
const latest=[r('Q27',0,'있다'),r('Q27',1,'없다'),r('Q27',2,'있다','없다'),r('Q33',0,'대상 학생이 없다'),r('Q35',-1,'학생회 선거'),r('Q37',-1,'배구'),r('Q46',0,'변경 예정'),r('Q47',1,'증가 예정'),r('Q48',0,'계속 운영(단계 변경 포함)'),r('Q31',-1,'있는 것으로 알고 있다'),r('Q51',-1,'있다'),r('Q40',0,'잘 모르겠다')];
const pick=(tier)=>F.collectFacts(historical,latest,tier,selections);
assert.equal(pick(0).length,0);
assert.ok(pick(1).every(x=>x.year===2025));
const a=pick(2),find=(year,q,index)=>a.find(x=>x.id===year+':'+q+':'+index);
assert.equal(find(2025,'Q31',0).active,true);
assert.equal(find(2025,'Q32',0).active,false);
assert.equal(find(2025,'Q38',0),undefined);
assert.equal(find(2025,'Q06',0),undefined);
assert.equal(find(2025,'Q09',0),undefined);
assert.equal(find(2025,'Q03',1).active,true);
assert.equal(find(2025,'Q03',0),undefined);
assert.equal(find(2025,'Q04',0).active,false);
assert.equal(find(2026,'Q27',0).active,true);
assert.equal(find(2026,'Q27',1).active,false);
assert.equal(find(2026,'Q27',2),undefined);
assert.equal(find(2026,'Q33',0),undefined);
assert.equal(find(2026,'Q37',0).active,true);
assert.equal(find(2026,'Q37',1),undefined);
assert.equal(find(2026,'Q31',0),undefined);
assert.equal(find(2026,'Q51',0),undefined);
assert.equal(find(2026,'Q40',0),undefined);
assert.equal(find(2026,'Q47',1).label,'학생 수 변경 예정');
assert.equal(find(2026,'Q48',0).active,true);
const all=Object.entries(C).flatMap(([q,v])=>v.kind==='grid'?v.rows.map((_,i)=>r(q,i,v.columns[0])):v.kind==='multi'?[r(q,-1,...v.options.filter(x=>!x.includes('없다')&&!x.includes('모르겠다')&&!x.includes('운영하지 않는다')))]:v.kind==='choice'?[r(q,-1,v.options[0])]:[]);
const facts=F.collectFacts([],all,2);assert.ok(facts.length>=95);assert.ok(facts.every(x=>x.questionId!=='Q31'&&x.questionId!=='Q51'));
console.log('PASS',facts.length,'2026 factual icon candidates; year gates, exact choices, explicit negatives, exclusions and future plans');

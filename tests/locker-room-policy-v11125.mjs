import assert from "node:assert/strict";
import {validateDraft,canRead,canWrite,displayName,projectPost,selectFeed,validateReply,notificationRecipient} from "../supabase/functions/_shared/locker-room-policy-v11125.mjs";
const viewer={level:2,accountVerified:true,actorId:"a",suspended:false};
const post={id:"p",body:"학교 이야기",subject_type:"school",school_id:"A123456",status:"published",created_at:"2026-11-26T00:00:00Z",author_uid:"a",thread_alias:"세터",author_role:"member",private_token:"never"};
const general={...post,id:"q",school_id:null,subject_type:"general",created_at:"2026-11-26T01:00:00Z",author_uid:"b",author_role:"operator"};
assert.equal(validateDraft({body:"가".repeat(300)}).subject_type,"general");
assert.throws(()=>validateDraft({body:"가".repeat(301)}),/INVALID_POST/);
assert.equal(validateDraft({body:"안녕",schoolId:"A123456"}).subject_type,"school");
assert.throws(()=>validateDraft({body:"안녕",schoolId:"bad"}),/INVALID_SCHOOL/);
assert.throws(()=>validateDraft({body:"010-1234-5678"}),/INVALID_POST/);
assert.throws(()=>validateDraft({body:"https://example.com"}),/INVALID_POST/);
assert.equal(canRead(post,{...viewer,level:1}),false);
assert.equal(canRead(post,{...viewer,accountVerified:false}),false);
assert.equal(canRead({...post,status:"hidden"},viewer),false);
assert.equal(canRead({...post,minimum_read_level:3},viewer),false);
assert.equal(canRead({...post,minimum_read_level:0},viewer),false);
assert.equal(canWrite({...viewer,suspended:true}),false);
assert.equal(canWrite(viewer),true);
assert.equal(displayName(general),"카리브해매너티");
assert.equal(displayName({...post,thread_alias:"카리브해매너티"}),"익명");
assert.equal(displayName({...post,thread_alias:"세터 2"}),"세터 2");
const projected=projectPost(post,viewer);
assert.equal(projected.mine,true);
assert.equal("author_uid" in projected,false);
assert.equal("private_token" in projected,false);
assert.deepEqual(selectFeed([post,general],viewer).map(p=>p.id),["q","p"]);
assert.deepEqual(selectFeed([post,general],viewer,{filter:"school"}).map(p=>p.id),["p"]);
assert.deepEqual(selectFeed([post,general],viewer,{filter:"operator"}).map(p=>p.id),["q"]);
assert.deepEqual(selectFeed([post,general],viewer,{schoolId:"A123456"}).map(p=>p.id),["p"]);
assert.deepEqual(selectFeed([post,general],{...viewer,level:0}),[]);
const parent={id:"c",post_id:"p",status:"published",author_uid:"b",parent_id:null};
assert.deepEqual(validateReply(post,parent,viewer),{post_id:"p",parent_id:"c"});
assert.throws(()=>validateReply(post,{...parent,post_id:"q"},viewer),/INVALID_PARENT/);
assert.throws(()=>validateReply(post,{...parent,parent_id:"x"},viewer),/INVALID_PARENT/);
assert.throws(()=>validateReply(post,{...parent,status:"hidden"},viewer),/INVALID_PARENT/);
assert.equal(notificationRecipient(post,parent,"a"),"b");
assert.equal(notificationRecipient(post,null,"a"),null);
console.log("locker-room policy: 30 assertions passed");

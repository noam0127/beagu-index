import assert from "node:assert/strict";
import fs from "node:fs";
const read=p=>fs.readFileSync(p,"utf8");
const t=read("supabase/functions/beagu-release-manager-v1/index.ts");
const w=read("scripts/release-manager/worker.py");
const s=read("scripts/release-manager/vercel_stage.py");
const y=read(".github/workflows/beagu-release-controller.yml");
assert.equal(JSON.parse(read("vercel.json")).git.deploymentEnabled,false);
assert.match(t,/input\.verified_stage_sha!==job\.to_sha/);
assert.match(t,/verifiedStage\?\.deployed_url!=="https:\/\/baegu-index-test\.vercel\.app\/"/);
const stage=t.split('{staging_sha:job.to_sha,staging_version:job.version,')[1].split('}:')[0];
assert.doesNotMatch(stage,/public_data_blob_sha|production_sha/);
assert.match(w,/Staging jobs must use the independent Vercel worker/);
assert.doesNotMatch(w,/archive\(staging,/);
assert.match(s,/live\.get\("productionBaseline"\)!=sha/);
assert.match(s,/alias.*!=deployment/);
assert.match(y,/outputs\.target == 'staging'/);
assert.match(y,/outputs\.target == 'production'/);
assert.match(read("admin-updates.html"),/https:\/\/baegu-index-test\.vercel\.app\//);
console.log("independent staging routing and isolation static checks passed");
